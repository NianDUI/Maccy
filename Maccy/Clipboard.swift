import AppKit
import Defaults
import OSLog
import Sauce

private final class ClipboardRepresentationProvider: NSObject, NSPasteboardItemDataProvider {
  private let type: NSPasteboard.PasteboardType
  private let reference: PayloadReference?
  private let content: HistoryItemContent

  private let payloadStore: PayloadStore

  init(content: HistoryItemContent, payloadStore: PayloadStore) {
    self.type = NSPasteboard.PasteboardType(content.type)
    self.reference = content.payloadVerifiedAt == nil ? nil : content.payloadReference
    // Keep the model object rather than faulting its potentially large inline
    // BLOB while registering the provider. If the verified external file later
    // becomes unavailable, the provider can still fault the retained inline
    // compatibility copy on demand.
    self.content = content
    self.payloadStore = payloadStore
  }

  func pasteboard(
    _ pasteboard: NSPasteboard?,
    item: NSPasteboardItem,
    provideDataForType type: NSPasteboard.PasteboardType
  ) {
    guard type == self.type else { return }
    guard let data = reference.flatMap({ try? payloadStore.read($0, operation: .paste) }) ?? content.value else {
      return
    }
    item.setData(data, forType: type)
  }
}

class Clipboard {
  static let shared = Clipboard()

  typealias OnNewCopyHook = (HistoryItem) -> Void

  private var onNewCopyHooks: [OnNewCopyHook] = []
  var changeCount: Int

  private let pasteboard = NSPasteboard.general
  private let payloadStore: PayloadStore
  private let logger = Logger(subsystem: "org.p0deje.Maccy", category: "ClipboardPayload")

  private var timer: Timer?
  private var activeDataProviders: [ClipboardRepresentationProvider] = []

  private let dynamicTypePrefix = "dyn."
  private let microsoftSourcePrefix = "com.microsoft.ole.source."
  private let supportedTypes: Set<NSPasteboard.PasteboardType> = [
    .fileURL,
    .html,
    .png,
    .rtf,
    .string,
    .tiff
  ]
  private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
    .autoGenerated,
    .concealed,
    .transient
  ]
  private let unpersistableTypes: Set<NSPasteboard.PasteboardType> = [
    .appleWebArchive,
    .safariWebArchve
  ]

  private var enabledTypes: Set<NSPasteboard.PasteboardType> { Defaults[.enabledPasteboardTypes] }
  private var disabledTypes: Set<NSPasteboard.PasteboardType> { supportedTypes.subtracting(enabledTypes) }

  private var sourceApp: NSRunningApplication? { NSWorkspace.shared.frontmostApplication }

  init(payloadStore: PayloadStore = .shared) {
    self.payloadStore = payloadStore
    changeCount = pasteboard.changeCount
  }

  func onNewCopy(_ hook: @escaping OnNewCopyHook) {
    onNewCopyHooks.append(hook)
  }

  func clearHooks() {
    onNewCopyHooks = []
  }

  func start() {
    timer = Timer.scheduledTimer(
      timeInterval: Defaults[.clipboardCheckInterval],
      target: self,
      selector: #selector(checkForChangesInPasteboard),
      userInfo: nil,
      repeats: true
    )
  }

  func restart() {
    timer?.invalidate()
    start()
  }

  func stop() {
    timer?.invalidate()
    timer = nil
  }

  func isPersistable(_ type: NSPasteboard.PasteboardType) -> Bool {
    return !unpersistableTypes.contains(type) &&
             !type.rawValue.hasPrefix(microsoftSourcePrefix) &&
             !type.rawValue.hasPrefix(dynamicTypePrefix)
  }

  @MainActor
  func copyInMaccy(_ string: String) {
    pasteboard.clearContents()
    pasteboard.setString(string, forType: .string)
    pasteboard.setString(NSPasteboard.PasteboardType.fromMaccy.rawValue, forType: .source)
    sync()
    checkForChangesInPasteboard()
  }

  @MainActor
  func copy(_ item: HistoryItem?, removeFormatting: Bool = false) {
    guard let item else { return }

    pasteboard.clearContents()
    var contents = item.contents

    if removeFormatting {
      contents = clearFormatting(contents)
    }

    if item.manifestVersion > 0 && StorageRollout.manifestReplayEnabled {
      copyManifest(item, contents: contents)
    } else {
      copyLegacy(item, contents: contents)
    }

    sync()

    Task {
      Notifier.notify(body: item.title, sound: .knock)
      checkForChangesInPasteboard()
    }
  }

  private func copyLegacy(_ item: HistoryItem, contents: [HistoryItemContent]) {
    activeDataProviders.removeAll()

    for content in contents {
      guard content.type != NSPasteboard.PasteboardType.fileURL.rawValue else { continue }
      pasteboard.setData(content.resolvedValue, forType: NSPasteboard.PasteboardType(content.type))
    }

    // Use writeObjects for file URLs so that multiple files that are copied actually work.
    // Only do this for file URLs because it causes an issue with some other data types (like formatted text)
    // where the item is pasted more than once.
    let fileURLItems: [NSPasteboardItem] = contents.compactMap { item in
      guard item.type == NSPasteboard.PasteboardType.fileURL.rawValue else { return nil }
      guard let value = item.resolvedValue else { return nil }
      let pasteItem = NSPasteboardItem()
      pasteItem.setData(value, forType: NSPasteboard.PasteboardType(item.type))
      return pasteItem
    }
    pasteboard.writeObjects(fileURLItems)

    pasteboard.setString("", forType: .fromMaccy)
    pasteboard.setString(item.application ?? "", forType: .source)
  }

  private func copyManifest(_ historyItem: HistoryItem, contents: [HistoryItemContent]) {
    let grouped = Dictionary(grouping: contents, by: \.itemIndex)
    var providers: [ClipboardRepresentationProvider] = []
    var pasteboardItems: [NSPasteboardItem] = []

    for itemIndex in grouped.keys.sorted() {
      guard let representations = grouped[itemIndex] else { continue }
      let pasteboardItem = NSPasteboardItem()

      for content in representations.sorted(by: { $0.representationIndex < $1.representationIndex }) {
        let provider = ClipboardRepresentationProvider(content: content, payloadStore: payloadStore)
        providers.append(provider)
        pasteboardItem.setDataProvider(
          provider,
          forTypes: [NSPasteboard.PasteboardType(content.type)]
        )
      }

      pasteboardItems.append(pasteboardItem)
    }

    guard let firstItem = pasteboardItems.first else { return }
    firstItem.setString("", forType: .fromMaccy)
    firstItem.setString(historyItem.application ?? "", forType: .source)
    activeDataProviders = providers
    pasteboard.writeObjects(pasteboardItems)
  }

  // Based on https://github.com/Clipy/Clipy/blob/develop/Clipy/Sources/Services/PasteService.swift.
  func paste() {
    Accessibility.check()

    // Add flag that left/right modifier key has been pressed.
    // See https://github.com/TermiT/Flycut/pull/18 for details.
    let cmdFlag = CGEventFlags(rawValue: UInt64(KeyChord.pasteKeyModifiers.rawValue) | 0x000008)
    var vCode = Sauce.shared.keyCode(for: KeyChord.pasteKey)

    // Force QWERTY keycode when keyboard layout switches to
    // QWERTY upon pressing ⌘ key (e.g. "Dvorak - QWERTY ⌘").
    // See https://github.com/p0deje/Maccy/issues/482 for details.
    if KeyboardLayout.current.commandSwitchesToQWERTY && cmdFlag.contains(.maskCommand) {
      vCode = KeyChord.pasteKey.QWERTYKeyCode
    }

    let source = CGEventSource(stateID: .combinedSessionState)
    // Disable local keyboard events while pasting
    source?.setLocalEventsFilterDuringSuppressionState([.permitLocalMouseEvents, .permitSystemDefinedEvents],
                                                       state: .eventSuppressionStateSuppressionInterval)

    let keyVDown = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: true)
    let keyVUp = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: false)
    keyVDown?.flags = cmdFlag
    keyVUp?.flags = cmdFlag
    keyVDown?.post(tap: .cgSessionEventTap)
    keyVUp?.post(tap: .cgSessionEventTap)
  }

  func clear() {
    guard Defaults[.clearSystemClipboard] else {
      return
    }

    pasteboard.clearContents()
  }

  @objc
  @MainActor
  func checkForChangesInPasteboard() { // swiftlint:disable:this cyclomatic_complexity
    guard pasteboard.changeCount != changeCount else {
      return
    }

    changeCount = pasteboard.changeCount

    if pasteboard.pasteboardItems?.contains(where: { $0.types.contains(.fromMaccy) }) != true {
      // External copy occurred. Stop the current paste stack.
      // Maybe queue it into the paste stack? Configurable behaviour?
      AppState.shared.history.interruptPasteStack()
    }

    if Defaults[.ignoreEvents] {
      if Defaults[.ignoreOnlyNextEvent] {
        Defaults[.ignoreEvents] = false
        Defaults[.ignoreOnlyNextEvent] = false
      }

      return
    }

    // Reading types on NSPasteboard gives all the available
    // types - even the ones that are not present on the NSPasteboardItem.
    // See https://github.com/p0deje/Maccy/issues/241.
    if shouldIgnore(Set(pasteboard.types ?? [])) {
      return
    }

    if let sourceAppBundle = sourceApp?.bundleIdentifier, shouldIgnore(sourceAppBundle) {
      return
    }

    // Some applications (BBEdit, Edge) add 2 items to pasteboard when copying
    // so it's better to merge all data into a single record.
    // - https://github.com/p0deje/Maccy/issues/78
    // - https://github.com/p0deje/Maccy/issues/472
    var contents = [HistoryItemContent]()
    pasteboard.pasteboardItems?.enumerated().forEach({ itemIndex, item in
      var types = item.types
      if types.contains(.string) && isEmptyString(item) && !richText(item) {
        return
      }

      if shouldIgnore(item) {
        return
      }

      types = types
        .filter { !disabledTypes.contains($0) && isPersistable($0) }

      // Avoid reading Microsoft Word links from bookmarks and cross-references.
      // https://github.com/p0deje/Maccy/issues/613
      // https://github.com/p0deje/Maccy/issues/770
      if Set(types).isSuperset(of: [.microsoftLinkSource, .microsoftObjectLink]) {
        types.removeAll { [.microsoftLinkSource, .microsoftObjectLink, .pdf].contains($0) }
      }

      types.enumerated().forEach { representationIndex, type in
        contents.append(
          HistoryItemContent(
            type: type.rawValue,
            value: item.data(forType: type),
            itemIndex: itemIndex,
            representationIndex: representationIndex
          )
        )
      }
    })

    guard !contents.isEmpty else {
      return
    }

    let historyItem = HistoryItem(contents: contents)

    if #unavailable(macOS 15.0) {
      // On macOS 14 the history item needs to be inserted into storage directly after creating it.
      try? History.shared.insertIntoStorage(historyItem)
    }

    historyItem.application = sourceApp?.bundleIdentifier
    historyItem.title = historyItem.generateTitle()

    onNewCopyHooks.forEach({ $0(historyItem) })

    if StorageRollout.externalPayloadStorageEnabled {
      scheduleExternalization(for: historyItem)
    }
  }

  /// Pasteboard reads stay on the main actor, but hashing and file I/O do not.
  /// Inline bytes remain the durable fallback until every payload write has
  /// completed and the model context has saved its references.
  @MainActor
  func scheduleExternalization(for historyItem: HistoryItem) {
    let imageTypes = Set(StorageType.images.types.map(\.rawValue))
    let inputs = historyItem.contents.compactMap { content in
      content.value.map { (id: content.id, data: $0, isImage: imageTypes.contains(content.type)) }
    }
    guard !inputs.isEmpty else { return }
    let payloadStore = self.payloadStore
    let targetSize = HistoryItemDecorator.thumbnailImageSize
    let scale = NSScreen.forPopup?.backingScaleFactor ?? NSScreen.main?.backingScaleFactor ?? 1

    Task { @MainActor in
      let results = await Task.detached(priority: .utility) {
        var results: [(id: UUID, reference: PayloadReference?, imageSize: NSSize?)] = []
        for input in inputs {
          let reference = try? payloadStore.write(input.data)
          var imageSize: NSSize?
          if input.isImage, let reference {
            let cacheKey = reference.hash + "-\(Int(targetSize.width * scale))x\(Int(targetSize.height * scale))"
            imageSize = await ThumbnailDecodeScheduler.shared.cachedOrGenerate(
              cacheKey: cacheKey,
              reference: reference,
              inlineData: nil,
              knownOriginalSize: nil,
              targetSize: targetSize,
              scale: scale,
              payloadStore: payloadStore
            )?.originalPixelSize
          }
          results.append((input.id, reference, imageSize))
        }
        return results
      }.value

      for result in results {
        guard let reference = result.reference,
              let content = historyItem.contents.first(where: { $0.id == result.id }) else { continue }
        content.recordVerifiedPayload(reference)
        if let imageSize = result.imageSize {
          historyItem.recordImagePixelSize(imageSize)
        }
      }
      historyItem.refreshMetadata()
      do {
        // Persist verified references before removing any inline fallback.
        try Storage.shared.context.save()
        if StorageRollout.verifiedInlinePayloadCleanupEnabled {
          for result in results {
            guard result.reference != nil,
                  let content = historyItem.contents.first(where: { $0.id == result.id }) else { continue }
            try content.removeInlineValueIfVerified(store: payloadStore)
          }
          try Storage.shared.context.save()
        }
      } catch {
        logger.error("External payload persistence failed: \(String(reflecting: error), privacy: .public)")
      }
    }
  }

  private func shouldIgnore(_ types: Set<NSPasteboard.PasteboardType>) -> Bool {
    let ignoredTypes = self.ignoredTypes
      .union(Defaults[.ignoredPasteboardTypes].map({ NSPasteboard.PasteboardType($0) }))

    return types.isDisjoint(with: enabledTypes) ||
      !types.isDisjoint(with: ignoredTypes)
  }

  private func shouldIgnore(_ sourceAppBundle: String) -> Bool {
    if Defaults[.ignoreAllAppsExceptListed] {
      return !Defaults[.ignoredApps].contains(sourceAppBundle)
    } else {
      return Defaults[.ignoredApps].contains(sourceAppBundle)
    }
  }

  private func shouldIgnore(_ item: NSPasteboardItem) -> Bool {
    for regexp in Defaults[.ignoreRegexp] {
      if let string = item.string(forType: .string) {
        do {
          let regex = try NSRegularExpression(pattern: regexp)
          if regex.numberOfMatches(in: string, range: NSRange(string.startIndex..., in: string)) > 0 {
            return true
          }
        } catch {
          return false
        }
      }
    }
    return false
  }

  private func isEmptyString(_ item: NSPasteboardItem) -> Bool {
    guard let string = item.string(forType: .string) else {
      return true
    }

    return string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
  }

  private func richText(_ item: NSPasteboardItem) -> Bool {
    if let rtf = item.data(forType: .rtf) {
      if let attributedString = NSAttributedString(rtf: rtf, documentAttributes: nil) {
        return !attributedString.string.isEmpty
      }
    }

    if let html = item.data(forType: .html) {
      if let attributedString = NSAttributedString(html: html, documentAttributes: nil) {
        return !attributedString.string.isEmpty
      }
    }

    return false
  }

  // Some applications requires window be unfocused and focused back to sync the clipboard.
  // - Chrome Remote Desktop (https://github.com/p0deje/Maccy/issues/948)
  // - Netbeans (https://github.com/p0deje/Maccy/issues/879)
  private func sync() {
    guard let app = sourceApp,
          app.bundleURL?.lastPathComponent == "Chrome Remote Desktop.app" ||
            app.localizedName?.contains("NetBeans") == true else {
      return
    }

    NSApp.activate(ignoringOtherApps: true)
    NSApp.hide(self)
  }

  private func clearFormatting(_ contents: [HistoryItemContent]) -> [HistoryItemContent] {
    var newContents: [HistoryItemContent] = contents
    let stringContents = contents.filter { NSPasteboard.PasteboardType($0.type) == .string }

    // If there is no string representation of data,
    // behave like we didn't have to remove formatting.
    if !stringContents.isEmpty {
      newContents = stringContents

      // Preserve file URLs.
      // https://github.com/p0deje/Maccy/issues/962
      let fileURLContents = contents.filter { NSPasteboard.PasteboardType($0.type) == .fileURL }
      if !fileURLContents.isEmpty {
        newContents += fileURLContents
      }
    }

    return newContents
  }
}
